function classifyDiscipline(subject: Subject): keyof typeof BLUEPRINTS {
  const n = subject.subjectName.toLowerCase();
  if (n.includes('account')) return 'accountancy';
  if (n.includes('business')) return 'business_studies';
  if (n.includes('econom')) return 'economics';
  if (n.includes('political')) return 'political_science';
  if (n.includes('history') && !n.includes('civics')) return 'history';
  if (n.includes('social') || n.includes('civics') || n.includes('geography')) return 'social_science';
  if (n.includes('sanskrit')) return 'sanskrit';
  if (n.includes('hindi')) return 'hindi';
  if (n.includes('english')) return 'english';
  if (n.includes('physics')) return 'physics';
  if (n.includes('chem')) return 'chemistry';
  if (n.includes('bio')) return 'biology';
  if (n.includes('math')) return 'mathematics';
  return 'science';
}

export function buildExpandedCurriculum(
  baseSubjects: Subject[],
  baseChapters: Chapter[],
  baseTopics: Topic[],
  baseQuestions: Question[],
  baseMaterials: LearningMaterial[]
) {
  const subjectMap = new Map<string, Subject>();
  for (const s of baseSubjects) subjectMap.set(s.id, s);
  for (const s of EXPANSION_SUBJECTS) {
    if (!subjectMap.has(s.id)) subjectMap.set(s.id, s);
  }
  const allSubjects = Array.from(subjectMap.values());

  const allChapters = [...baseChapters];
  const allTopics = [...baseTopics];
  const allQuestions = [...baseQuestions];
  const allMaterials = [...baseMaterials];

  for (const subj of allSubjects) {
    const disciplineKey = classifyDiscipline(subj);
    const bp = BLUEPRINTS[disciplineKey];

    // Existing chapters for this subject
    let subjChapters = allChapters.filter((c) => c.subjectId === subj.id);
    if (subjChapters.length < 2) {
      const existingNums = new Set(subjChapters.map((c) => c.chapterNumber));
      for (let i = 0; i < bp.chapters.length; i++) {
        const chTpl = bp.chapters[i];
        const chNum = existingNums.has(chTpl.chapterNumber) ? subjChapters.length + 2 : chTpl.chapterNumber;
        const chId = `ch_${subj.id}_exp_${i + 1}`;
        if (!allChapters.some((c) => c.id === chId)) {
          const newCh: Chapter = {
            id: chId,
            subjectId: subj.id,
            unitName: chTpl.unitName,
            chapterNumber: chNum,
            chapterName: chTpl.chapterName,
            introduction: chTpl.introduction,
            completeExplanation: chTpl.completeExplanation,
            learningObjectives: chTpl.learningObjectives,
            definitions: chTpl.definitions,
            importantFacts: chTpl.importantFacts,
            formulas: chTpl.formulas,
            examples: chTpl.examples,
            diagrams: [],
            revisionNotes: chTpl.revisionNotes,
            syllabusStatus: subj.status,
            sourceReference: `${subj.boardId.toUpperCase()} ${subj.classId.replace('_', ' ').toUpperCase()} ${subj.subjectName} Reference Blueprint`,
            published: true,
          };
          allChapters.push(newCh);
          subjChapters.push(newCh);

          chTpl.topics.forEach((topName, tIdx) => {
            allTopics.push({
              id: `top_${chId}_${tIdx + 1}`,
              chapterId: chId,
              orderIndex: tIdx + 1,
              topicName: topName,
              content: chTpl.completeExplanation,
              difficulty: tIdx === 0 ? 'Foundation' : 'Standard',
            });
          });
        }
      }
    }

    // Ensure every subject has subject-specific multi-type questions (never falling back to Math!)
    const existingSubjQuestions = allQuestions.filter((q) => q.subjectId === subj.id);
    if (existingSubjQuestions.length < 5) {
      const firstCh = subjChapters[0];
      const secondCh = subjChapters[1] || subjChapters[0];

      bp.questions.forEach((qTpl, qIdx) => {
        const targetCh = qTpl.chapterOffset === 1 ? secondCh : firstCh;
        const qId = `q_${subj.id}_exp_${qIdx + 1}`;
        if (!allQuestions.some((q) => q.id === qId) && targetCh) {
          allQuestions.push({
            id: qId,
            boardId: subj.boardId,
            classId: subj.classId,
            academicSessionId: subj.academicSessionId,
            subjectId: subj.id,
            chapterId: targetCh.id,
            topicName: qTpl.topicName,
            questionText: qTpl.questionText,
            questionType: qTpl.questionType,
            options: qTpl.options,
            correctAnswer: qTpl.correctAnswer,
            correctAnswers: qTpl.correctAnswers,
            matchPairs: qTpl.matchPairs,
            diagramSvg: qTpl.diagramSvg,
            explanation: qTpl.explanation,
            modelAnswer: qTpl.modelAnswer,
            rubricPoints: qTpl.rubricPoints,
            marks: qTpl.marks,
            priority: qTpl.priority,
            isPyq: false,
            sourceType: 'Teacher Curated Practice',
            sourceDocumentRef: `${subj.boardId.toUpperCase()} ${subj.subjectName} Curated Bank`,
            verificationStatus: 'Under Review',
            published: true,
          });
        }
      });

      // Add a matching Study Library summary material if none exists
      if (!allMaterials.some((m) => m.subjectId === subj.id) && firstCh) {
        allMaterials.push({
          id: `mat_${subj.id}_digest`,
          chapterId: firstCh.id,
          subjectId: subj.id,
          boardId: subj.boardId,
          classId: subj.classId,
          materialType: 'Chapter Summary',
          title: `${subj.subjectName} — Quick Revision & Formula Digest`,
          content: `${firstCh.chapterName}:\n${firstCh.revisionNotes}\n\nKey Definitions:\n${firstCh.definitions
            .map((d) => `• ${d.term}: ${d.meaning}`)
            .join('\n')}`,
          sourceCitation: 'Teacher Curated Summary (Reference Study Aid)',
          verificationStatus: 'Under Review',
          published: true,
          createdBy: 'system',
          createdAt: '2026-04-01T00:00:00Z',
        });
      }
    }
  }

  return {
    subjects: allSubjects,
    chapters: allChapters,
    topics: allTopics,
    questions: allQuestions,
    materials: allMaterials,
  };
}

